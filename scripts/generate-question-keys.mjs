// Generates the server-side answer-key migration from the question JSON files.
// Run after changing any question data:  node scripts/generate-question-keys.mjs
// sort_order must match data/questions.ts (PDF number; originals start at 100).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, f), "utf8"));
const src = read("data/source-questions.json");
const meta = read("data/question-meta.json");
const originals = read("data/original-questions.json");

const rows = [
  ...src.map((q) => ({
    id: `pdf-${String(q.number).padStart(2, "0")}`,
    sort: q.number,
    answers: [q.answer],
    mode: meta[String(q.number)].gameMode,
    concept: meta[String(q.number)].conceptId,
  })),
  ...originals.map((q, i) => ({ id: q.id, sort: 100 + i, answers: q.correctAnswers, mode: q.gameMode, concept: q.conceptId })),
];

const esc = (s) => `'${String(s).replace(/'/g, "''")}'`;
const values = rows
  .map((r) => `  (${esc(r.id)}, ${r.sort}, array[${r.answers.map(esc).join(", ")}], ${esc(r.mode)}, ${esc(r.concept)})`)
  .join(",\n");

const sql = `-- GENERATED by scripts/generate-question-keys.mjs. Do not edit by hand.
-- Server-side answer keys for ${rows.length} questions (${src.length} from the PDF, ${originals.length} DesignXP originals).
insert into public.question_keys (id, sort_order, correct_answers, game_mode, concept_id) values
${values}
on conflict (id) do update set
  sort_order = excluded.sort_order,
  correct_answers = excluded.correct_answers,
  game_mode = excluded.game_mode,
  concept_id = excluded.concept_id;
`;
fs.writeFileSync(path.join(root, "supabase/migrations/20261123000100_question_keys.sql"), sql);
console.log(`Wrote ${rows.length} question keys.`);
